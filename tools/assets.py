#!/usr/bin/env python3
"""Generate immutable banks and patterns from the preserved user assets."""
from pathlib import Path
import json, struct, zlib
root = Path(__file__).resolve().parents[1]
names = ['tamborzao','voltmix','bolha']
racks = json.loads((root/'assets/audio/racks.json').read_text())
out = ['/* Generated by tools/assets.py. User supplied audio, not an open-content grant. */']
patterns = []
for kit in names:
    bank = (root/'assets/audio'/f'{kit}.fm1s').read_bytes()
    magic, version, size, crc, commit, rate = struct.unpack_from('<6I',bank)
    assert (magic,version,size,commit,rate) == (0x53314d46,1,len(bank),0,32000)
    assert zlib.crc32(bank[:12]+bytes(8)+bank[20:]) == crc
    next_offset = 512
    for pad in range(16):
        offset, frames, count = struct.unpack_from('<3I',bank,32+pad*28)
        assert offset == next_offset and count == ((frames+319)//320)*228
        assert pad < 4 or not frames
        for at in range(offset,offset+count,228): assert bank[at:at+4] == b'\x01\x45\x14\x5a'
        next_offset += count
    assert next_offset == len(bank)
    out.append(f'static const unsigned char bank_{kit}[] __attribute__((aligned(4))) = {{')
    out += [','.join(map(str,bank[i:i+24]))+',' for i in range(0,len(bank),24)]
    out.append('};')
    meta = json.loads((root/'assets/audio/tamborzao.json').read_text()) if kit == 'tamborzao' else racks[kit]
    masks = [0]*4
    for n in meta['notes']:
        part = n['midi']-(36 if kit == 'tamborzao' else 60)
        step = min(31 if kit == 'tamborzao' else 15,int(n['beat']*4+0.5))
        assert 0 <= part < 4 and step >= 0
        masks[part] |= 1 << step
    if kit != 'tamborzao': masks = [v | (v << 16) for v in masks]
    patterns.append(masks)
out += ['static const unsigned char *const banks[3] = {bank_tamborzao,bank_voltmix,bank_bolha};',
        'static const unsigned bank_sizes[3] = {sizeof bank_tamborzao,sizeof bank_voltmix,sizeof bank_bolha};',
        'static const uint32_t factory_steps[3][4] = {']
out += ['{'+','.join(hex(v)+'U' for v in m)+'},' for m in patterns]
out.append('};')
(root/'app/baile_assets.inc').write_text('\n'.join(out)+'\n')
print('Validated 3 banks / 12 samples; generated source-derived 32-step patterns.')
